#!/usr/bin/env python3
"""Generate docs/STDLIB.md from `///` doc comments in stdlib/std/src/*.misa.

Usage: python3 stdlib/gen_docs.py   (run from the repo root)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "stdlib", "std", "src")
OUT = os.path.join(ROOT, "docs", "STDLIB.md")
MODULES = ["strings", "lists", "json", "http", "result"]


def parse(path):
    """Yield (kind, name, sig, doc_lines) for documented fn/type decls."""
    items = []
    docs = []
    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.strip()
            if line.startswith("///"):
                docs.append(line[3:].strip())
            elif line.startswith("fn ") or line.startswith("type "):
                sig = line.split("{")[0].strip()
                kind = "fn" if line.startswith("fn ") else "type"
                name = sig.split()[1].split("(")[0]
                items.append((kind, name, sig, docs))
                docs = []
            elif line:
                docs = []  # stray doc comment; do not attach
    return items


def main():
    out = []
    out.append("# Misa Standard Library (`std`)")
    out.append("")
    out.append("Bundled with the toolchain. Import a module by path:")
    out.append("")
    out.append("```misa")
    out.append('import "std/strings"')
    out.append("```")
    out.append("")
    out.append('`import "std"` loads every module. Imports share one flat')
    out.append("namespace with your program (a duplicate name is E110).")
    out.append("")
    out.append("> Generated by `python3 stdlib/gen_docs.py` — do not edit by hand.")
    out.append("")
    for mod in MODULES:
        path = os.path.join(SRC, mod + ".misa")
        if not os.path.isfile(path):
            continue
        out.append(f"## `std/{mod}`")
        out.append("")
        for kind, name, sig, docs in parse(path):
            out.append(f"### `{sig}`")
            out.append("")
            for d in docs:
                out.append(d)
            out.append("")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    sys.exit(main())
